"""Export the 120-month walk-forward series behind the guide's replay chart.

Reruns Part B1's walk-forward (same data, same rules as mvo_retest.py) for five
rules and writes their monthly excess returns, the T-bill rate, and quarterly
weights for the two optimizer rules. Before writing, it recomputes each rule's
annualized Sharpe ratio for every period in results.json from the rounded
series and stops if any differs by more than 0.002.

Usage:
    python3 export_replay.py                   # writes replay.json
    python3 export_replay.py --ts PATH.ts      # also writes the Summitward data module
"""

import argparse
import json
import math

import numpy as np

from mvo_retest import HERE, load_industries, make_rules, walk_forward

WINDOW = 120
RULES = [
    "equal_weight",
    "market_cap",
    "max_sharpe_sample",
    "min_var_long_only",
    "max_sharpe_const_sharpe",
]
WEIGHT_RULES = ["max_sharpe_sample", "min_var_long_only"]


def round_to_100(w):
    """Integer percents that sum to exactly 100 (largest remainder)."""
    raw = np.asarray(w) * 100
    base = np.floor(raw).astype(int)
    short = 100 - base.sum()
    order = np.argsort(-(raw - base))
    base[order[:short]] += 1
    return base.tolist()


def build():
    cols, dates, ex, rf, cap = load_industries()
    n = ex.shape[1]

    def market_cap(_x, _e, t):
        c = cap[t]
        return c / c.sum(), False

    all_rules = make_rules(n, {"market_cap": market_cap})
    res = walk_forward(ex, rf, WINDOW, {k: all_rules[k] for k in RULES})
    months = dates[WINDOW:].tolist()
    series = {k: [round(float(v) * 100, 3) for v in res[k][0]] for k in RULES}
    rf_pct = [round(float(v) * 100, 3) for v in rf[WINDOW:]]
    # weights chosen for each quarter's first month (Jan, Apr, Jul, Oct)
    q_idx = [i for i, d in enumerate(months) if d % 100 in (1, 4, 7, 10)]
    weights = {
        k: {"months": [months[i] for i in q_idx], "pct": [round_to_100(res[k][2][i]) for i in q_idx]}
        for k in WEIGHT_RULES
    }
    return {
        "source": "Kenneth French 10 value-weighted industry portfolios and F-F research factors",
        "window_months": WINDOW,
        "industries": cols,
        "months": months,
        "rf_pct": rf_pct,
        "excess_pct": series,
        "weights": weights,
    }


def check(out):
    published = json.loads((HERE / "results.json").read_text())["part_b1_industries"]
    by_period = published["by_window"][str(WINDOW)]
    months = np.array(out["months"])
    for pname, p in by_period.items():
        mask = (months >= p["first"]) & (months <= p["last"])
        for k in RULES:
            r = np.array(out["excess_pct"][k])[mask]
            s = r.mean() / r.std(ddof=1) * math.sqrt(12)
            want = p["strategies"][k]["sharpe"]
            if abs(s - want) > 0.002:
                raise SystemExit(f"{pname} {k}: {s:.4f} vs results.json {want}")
    print("Sharpe ratios match results.json for", ", ".join(by_period))


def write_ts(out, path):
    def arr(xs):
        return "[" + ",".join(f"{x:g}" for x in xs) + "]"

    lines = [
        "// Generated by summitward-research/mean-variance-optimization/export_replay.py.",
        "// Do not hand-edit; rerun the exporter. Walk-forward on Kenneth French's ten",
        "// value-weighted US industry portfolios, 120-month rolling window, monthly",
        "// rebalancing. Returns are monthly, in percent, in excess of the one-month T-bill.",
        "",
        f"export const REPLAY_INDUSTRIES = {json.dumps(out['industries'])} as const;",
        "",
        "/** Month of each walk-forward return, YYYYMM. */",
        f"export const REPLAY_MONTHS: number[] = {arr(out['months'])};",
        "",
        "/** One-month T-bill return, percent per month. */",
        f"export const REPLAY_RF: number[] = {arr(out['rf_pct'])};",
        "",
        "export const REPLAY_EXCESS = {",
    ]
    for k in RULES:
        lines.append(f"  {k}: {arr(out['excess_pct'][k])},")
    lines += ["};", "", "/** Weights chosen at each quarter's first month, integer percents summing to 100. */"]
    lines.append("export const REPLAY_WEIGHTS = {")
    for k in WEIGHT_RULES:
        w = out["weights"][k]
        rows = ",".join(arr(r) for r in w["pct"])
        lines.append(f"  {k}: {{ months: {arr(w['months'])}, pct: [{rows}] }},")
    lines += ["};", ""]
    with open(path, "w") as f:
        f.write("\n".join(lines))
    print("wrote", path)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ts", help="path of the TypeScript data module to write")
    args = ap.parse_args()
    out = build()
    check(out)
    (HERE / "replay.json").write_text(json.dumps(out, separators=(",", ":")))
    print("wrote replay.json")
    if args.ts:
        write_ts(out, args.ts)


if __name__ == "__main__":
    main()
